package main

import (
	"fmt"
	"image"
	_ "image/png"
	"os"
	"strings"
)

func main() {
	f, e := os.Open("../../assets/logo.png")
	if e != nil {
		panic(e)
	}
	defer f.Close()
	img, _, e := image.Decode(f)
	if e != nil {
		panic(e)
	}
	var b strings.Builder
	b.WriteString("// Code generated by tools/logogen; DO NOT EDIT.\npackage theme\n\n")
	for _, size := range []struct {
		name string
		w, h int
	}{{"largePixels", 32, 32}, {"smallPixels", 14, 14}} {
		fmt.Fprintf(&b, "var %s = [][3]uint8{\n", size.name)
		// Crop the figure inside the CRT, excluding its wordmark.
		pixels := make([][3]uint8, size.w*size.h)
		for y := 0; y < size.h; y++ {
			for x := 0; x < size.w; x++ {
				x0, x1 := 160+x*640/size.w, 160+(x+1)*640/size.w
				y0, y1 := 96+y*610/size.h, 96+(y+1)*610/size.h
				var r, g, bl, n uint64
				for yy := y0; yy < y1; yy++ {
					for xx := x0; xx < x1; xx++ {
						rr, gg, bb, _ := img.At(xx, yy).RGBA()
						r += uint64(rr >> 8)
						g += uint64(gg >> 8)
						bl += uint64(bb >> 8)
						n++
					}
				}
				pixels[y*size.w+x] = [3]uint8{uint8(r / n), uint8(g / n), uint8(bl / n)}
			}
		}
		for y := 0; y < size.h; y++ {
			for x := 0; x < size.w; x++ {
				count := 0
				for dy := -1; dy <= 1; dy++ {
					for dx := -1; dx <= 1; dx++ {
						xx, yy := x+dx, y+dy
						if xx >= 0 && yy >= 0 && xx < size.w && yy < size.h && pixels[yy*size.w+xx][1] >= 55 {
							count++
						}
					}
				}
				c := pixels[y*size.w+x]
				if count < 5 {
					c = [3]uint8{11, 18, 11}
				}
				fmt.Fprintf(&b, "{%d,%d,%d},", c[0], c[1], c[2])
			}
			b.WriteByte('\n')
		}
		b.WriteString("}\n")
	}
	if e = os.WriteFile("logo_gen.go", []byte(b.String()), 0644); e != nil {
		panic(e)
	}
}
